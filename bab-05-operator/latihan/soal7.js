console.log(10 == "10");//true karena tidak membandingkan tipe
console.log(10 === "10");//false karena salah satu string 
console.log(false == 0);//true angka 0 di konverensi mnjadi false
console.log(false === 0);//false karena boolean dan number tidak sama
console.log(null == undefined);//true, sama sama nilai kosong
console.log(null === undefined);//false karena beda tipe